// Pad all rows of a prop frame to the max row width (spaces = transparent).
function mkProp(frame: string[]): string[] {
  const w = Math.max(...frame.map(r => r.length));
  return frame.map(r => (r + ' '.repeat(w)).slice(0, w));
}

